// edition : Original
// status : DONE
// date : 2026-10-15
//
// The founder design ledger: check every line against its source, then write LEDGER.md.
//   node ledger.mjs verify   reads each quoted source on the founder's PC and prints any line it cannot find
//   node ledger.mjs render   writes ../Page-Doc-Design-System/LEDGER.md from ../Page-Doc-Design-System/ledger.json
// A line is filed only when "verify" finds it word for word ("found") or it is read off his own image ("image").
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const DOC = path.join(here, "..", "Page-Doc-Design-System");
const DATA = path.join(DOC, "ledger.json");
const OUT = path.join(DOC, "LEDGER.md");
const BS = String.fromCharCode(92);

const norm = s => String(s)
  .split(BS + "n").join(" ")
  .split(BS + '"').join('"')
  .split(BS + "u0026").join("&")
  .split(BS + "u2019").join("'")
  .replace(/[‘’]/g, "'").replace(/[“”]/g, '"')
  .replace(/\s+/g, " ").toLowerCase();

function files(L, e) {
  const r = L.roots[e.src];
  if (!r || !r.local) return [];
  if (!e.file) return [r.local];
  const full = r.local + e.file;
  if (!full.includes("*")) return [full];
  const dir = path.dirname(full), pre = path.basename(full).replace("*", "");
  return fs.existsSync(dir) ? fs.readdirSync(dir).filter(f => f.startsWith(pre)).map(f => path.join(dir, f)) : [];
}

function verify(L) {
  const bad = [];
  for (const e of L.entries) {
    if (e.src === "IMG") continue;
    const needle = norm(e.match || e.words.split(" / ")[0]).slice(0, 48);
    let hit = null;
    for (const f of files(L, e)) {
      if (!fs.existsSync(f)) continue;
      const lines = fs.readFileSync(f, "utf8").split("\n");
      const n = lines.findIndex(l => norm(l).includes(needle));
      if (n >= 0) { hit = n + 1; break; }
    }
    if (hit === null) bad.push(`${e.id} ${e.src} ${e.file || ""}: ${needle}`);
  }
  console.log(bad.length ? `NOT FOUND ${bad.length}\n${bad.join("\n")}` : `PASS all ${L.entries.length} lines found or read off an image`);
  return bad.length ? 1 : 0;
}

function render(L) {
  const topics = [...new Set(L.entries.map(e => e.topic))];
  const where = e => {
    const r = L.roots[e.src];
    const at = e.line ? `:${e.line}` : "";
    if (e.src === "IMG") return `his image, ${e.file}`;
    return `${r.label}${e.file ? ` \`${e.file}${at}\`` : at ? ` line ${e.line}` : ""}`;
  };
  const out = [
    "# Founder design ledger",
    "edition : Original",
    "status : DONE",
    "date : 2026-10-15",
    "",
    "Every design ruling the founder gave, in his own words, with where he said it and when. Typos are his and stay. The design system (`DECISIONS.md`, `tokens.json`) cites these ids. Generated by `Page-Prog-Design-System/ledger.mjs render` from `ledger.json`; `ledger.mjs verify` checked every line against its source on 2026-10-15.",
    "",
    `${L.entries.length} lines. Sources:`,
    "",
    ...Object.entries(L.roots).filter(([k]) => L.entries.some(e => e.src === k)).map(([k, r]) => `- ${r.label}: ${r.about}`),
    "",
  ];
  for (const t of topics) {
    out.push(`## ${t}`, "", "| id | date | his words | where |", "|---|---|---|---|");
    for (const e of L.entries.filter(x => x.topic === t)) {
      const w = e.words.replace(/\|/g, "/") + (e.note ? ` (${e.note.replace(/\|/g, "/")})` : "");
      out.push(`| ${e.id} | ${e.date} | "${w}" | ${where(e)} |`);
    }
    out.push("");
  }
  out.push("## Not filed", "", ...L.held.map(h => `- ${h}`), "");
  fs.writeFileSync(OUT, out.join("\n"));
  console.log(`wrote ${path.relative(process.cwd(), OUT)} (${L.entries.length} lines)`);
}

const L = JSON.parse(fs.readFileSync(DATA, "utf8"));
const mode = process.argv[2];
if (mode === "verify") process.exitCode = verify(L);
else if (mode === "render") render(L);
else { console.log("usage: node ledger.mjs verify|render"); process.exitCode = 2; }
